// ActivityDiff describes how a single activity changed between two versions.
type ActivityDiff struct {
	Name        string
	Kind        string // "added", "removed", "changed"
	OldLine     int
	NewLine     int
	InputDiffs  []FieldDiff
	OutputDiffs []FieldDiff
}

// FieldDiff describes how a single input/output field changed.
type FieldDiff struct {
	Name    string
	Kind    string // "added", "removed", "changed"
	OldType string
	NewType string
}

// DiffResult holds the full difference between two .axm versions.
type DiffResult struct {
	HashChanged bool
	OldHash     string
	NewHash     string
	Activities  []ActivityDiff
}

// Diff compares two compiled modules and returns structural differences.
func Diff(oldSrc, newSrc []byte, oldMod, newMod *compiler.Module) *DiffResult {
	oldHash := fmt.Sprintf("%x", sha256.Sum256(oldSrc))
	newHash := fmt.Sprintf("%x", sha256.Sum256(newSrc))

	result := &DiffResult{
		OldHash: oldHash,
		NewHash: newHash,
	}
	if oldHash != newHash {
		result.HashChanged = true
	}

	oldActs := externalActivities(oldMod)
	newActs := externalActivities(newMod)

	oldByName := make(map[string]lang.ActivityDecl, len(oldActs))
	for _, a := range oldActs {
		oldByName[a.Name] = a
	}
	newByName := make(map[string]lang.ActivityDecl, len(newActs))
	for _, a := range newActs {
		newByName[a.Name] = a
	}

	// Added activities.
	for _, a := range newActs {
		if _, ok := oldByName[a.Name]; !ok {
			ad := ActivityDiff{Name: a.Name, Kind: "added", NewLine: a.Line}
			for _, f := range a.Input {
				ad.InputDiffs = append(ad.InputDiffs, FieldDiff{Name: f.Name, Kind: "added", NewType: inferBindingType(newMod, f)})
			}
			for _, f := range a.Output {
				ad.OutputDiffs = append(ad.OutputDiffs, FieldDiff{Name: f.Name, Kind: "added", NewType: f.Type})
			}
			result.Activities = append(result.Activities, ad)
		}
	}

	// Removed activities.
	for _, a := range oldActs {
		if _, ok := newByName[a.Name]; !ok {
			ad := ActivityDiff{Name: a.Name, Kind: "removed", OldLine: a.Line}
			for _, f := range a.Input {
				ad.InputDiffs = append(ad.InputDiffs, FieldDiff{Name: f.Name, Kind: "removed", OldType: inferBindingType(oldMod, f)})
			}
			for _, f := range a.Output {
				ad.OutputDiffs = append(ad.OutputDiffs, FieldDiff{Name: f.Name, Kind: "removed", OldType: f.Type})
			}
			result.Activities = append(result.Activities, ad)
		}
	}

	// Changed activities.
	for _, a := range newActs {
		oldA, ok := oldByName[a.Name]
		if !ok {
			continue
		}
		ad := ActivityDiff{Name: a.Name, Kind: "changed", OldLine: oldA.Line, NewLine: a.Line}

		oldIn := fieldMap(oldA.Input, oldMod)
		newIn := fieldMap(a.Input, newMod)
		ad.InputDiffs = diffFields(oldIn, newIn)

		oldOut := fieldTypeMap(oldA.Output)
		newOut := fieldTypeMap(a.Output)
		ad.OutputDiffs = diffFields(oldOut, newOut)

		if len(ad.InputDiffs) > 0 || len(ad.OutputDiffs) > 0 {
			result.Activities = append(result.Activities, ad)
		}
	}

	return result
}

func fieldMap(bindings []lang.Binding, mod *compiler.Module) map[string]string {
	m := make(map[string]string, len(bindings))
	for _, b := range bindings {
		m[b.Name] = inferBindingType(mod, b)
	}
	return m
}

func fieldTypeMap(fields []lang.FieldDecl) map[string]string {
	m := make(map[string]string, len(fields))
	for _, f := range fields {
		m[f.Name] = f.Type
	}
	return m
}

func diffFields(old, new map[string]string) []FieldDiff {
	var diffs []FieldDiff
	for name, newType := range new {
		oldType, ok := old[name]
		if !ok {
			diffs = append(diffs, FieldDiff{Name: name, Kind: "added", NewType: newType})
		} else if oldType != newType {
			diffs = append(diffs, FieldDiff{Name: name, Kind: "changed", OldType: oldType, NewType: newType})
		}
	}
	for name, oldType := range old {
		if _, ok := new[name]; !ok {
			diffs = append(diffs, FieldDiff{Name: name, Kind: "removed", OldType: oldType})
		}
	}
	sort.Slice(diffs, func(i, j int) bool { return diffs[i].Name < diffs[j].Name })
	return diffs
}

func externalActivities(module *compiler.Module) []lang.ActivityDecl {
	var activities []lang.ActivityDecl
	for _, activity := range module.Activities {
		if activity.Effect == "none" {
			continue
		}
		activities = append(activities, activity)
	}
	sort.Slice(activities, func(i, j int) bool {
		return activities[i].Name < activities[j].Name
	})
	return activities
}

func inferBindingType(module *compiler.Module, binding lang.Binding) string {
	refs := lang.ExprRefs(binding.Expr)
	if len(refs) != 1 {
		return "Any"
	}
	return inferRefType(module, refs[0])
}

func inferRefType(module *compiler.Module, ref string) string {
	if symbol, ok := module.Symbols[ref]; ok && symbol.Type != "" && symbol.Type != "Any" {
		return symbol.Type
	}
	parts := strings.Split(ref, ".")
	if len(parts) >= 2 {
		if fact, ok := module.Facts[parts[0]]; ok {
			for _, expose := range fact.Expose {
				if expose.Name == parts[1] {
					return inferBindingType(module, expose)
				}
			}
		}
		if symbol, ok := module.Symbols[parts[0]+"."+parts[1]]; ok && symbol.Type != "" {
			return symbol.Type
		}
	}
	return "Any"
}

func goType(typeName string) string {
	nullable := strings.HasSuffix(typeName, "?")
	base := strings.TrimSuffix(typeName, "?")
	typ := goBaseType(base)
	if nullable {
		return "*" + typ
	}
	return typ
}

func goBaseType(typeName string) string {
	switch typeName {
	case "String", "Time", "Duration":
		return "string"
	case "Bool":
		return "bool"
	case "Int":
		return "int"
	case "Float":
		return "float64"
	case "Object":
		return "map[string]any"
	case "Any":
		return "any"
	default:
		if strings.HasPrefix(typeName, "List<") && strings.HasSuffix(typeName, ">") {
			return "[]" + goType(strings.TrimSuffix(strings.TrimPrefix(typeName, "List<"), ">"))
		}
		if strings.HasPrefix(typeName, "Map<") {
			return "map[string]any"
		}
		return "any"
	}
}

func exportName(name string) string {
	parts := splitName(name)
	for i, part := range parts {
		if part == "" {
			continue
		}
		runes := []rune(part)
		runes[0] = unicode.ToUpper(runes[0])
		parts[i] = string(runes)
	}
	return strings.Join(parts, "")
}

func lowerSnake(name string) string {
	parts := splitName(name)
	for i, part := range parts {
		parts[i] = strings.ToLower(part)
	}
	return strings.Join(parts, "_")
}

func splitName(name string) []string {
	var parts []string
	var current []rune
	flush := func() {
		if len(current) > 0 {
			parts = append(parts, string(current))
			current = nil
		}
	}
	var prevLower bool
	for _, r := range name {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			flush()
			prevLower = false
			continue
		}
		if unicode.IsUpper(r) && prevLower {
			flush()
		}
		current = append(current, r)
		prevLower = unicode.IsLower(r) || unicode.IsDigit(r)
	}
	flush()
	return parts
}
