type Options struct {
	PackageName string
	SourcePath  string
	Source      []byte
	Format      string
}

type File struct {
	Name    string
	Content []byte
	Once    bool
}

func Generate(module *compiler.Module, opts Options) ([]File, error) {
	if module == nil {
		return nil, fmt.Errorf("module is required")
	}
	if opts.PackageName == "" {
		return nil, fmt.Errorf("package name is required")
	}
	domain := exportName(module.Domain)
	if domain == "" {
		return nil, fmt.Errorf("module domain is required")
	}
	base := lowerSnake(module.Domain)
	if base == "" {
		base = "axiom"
	}
	gen, err := generatedFile(module, opts, domain)
	if err != nil {
		return nil, err
	}
	stubs, err := stubsFile(module, opts, domain)
	if err != nil {
		return nil, err
	}
	return []File{
		{Name: base + "_axiom.gen.go", Content: gen},
		{Name: base + "_activities.go", Content: stubs, Once: true},
	}, nil
}

func generatedFile(module *compiler.Module, opts Options, domain string) ([]byte, error) {
	var b bytes.Buffer
	hash := sha256.Sum256(opts.Source)
	activities := externalActivities(module)
	comments := newCommentIndex(opts.Source)
	fmt.Fprintf(&b, "// Code generated by axiomgen from %s; DO NOT EDIT.\n\n", filepath.ToSlash(opts.SourcePath))
	fmt.Fprintf(&b, "package %s\n\n", opts.PackageName)
	fmt.Fprintln(&b, "import (")
	fmt.Fprintln(&b, "\t\"context\"")
	fmt.Fprintln(&b, "\t\"fmt\"")
	fmt.Fprintln(&b, "")
	fmt.Fprintln(&b, "\t\"github.com/Homiakus/axiom\"")
	if strings.EqualFold(opts.Format, "toml") {
		fmt.Fprintln(&b, "\t\"github.com/Homiakus/axiom/table\"")
	}
	fmt.Fprintln(&b, ")")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "const %sAXMHash = %q\n\n", domain, fmt.Sprintf("%x", hash[:]))
	fmt.Fprintf(&b, "const %sAXMSource = %q\n\n", domain, string(opts.Source))
	writeActivityNameConsts(&b, activities, comments)
	writeTypes(&b, module, activities, comments)
	writeInterface(&b, domain, activities, comments)
	writeLoadAndNew(&b, domain, activities, opts)
	writeAdapters(&b, module, activities)
	writeHelpers(&b)
	return format.Source(b.Bytes())
}

type commentIndex map[int][]string

func newCommentIndex(source []byte) commentIndex {
	text := strings.ReplaceAll(string(source), "\r\n", "\n")
	index := commentIndex{}
	var pending []string
	for i, line := range strings.Split(text, "\n") {
		lineNo := i + 1
		code, comment, hasComment := splitAXMComment(line)
		if strings.TrimSpace(code) == "" {
			if hasComment {
				pending = append(pending, comment)
			}
			continue
		}
		if len(pending) > 0 {
			index[lineNo] = append(index[lineNo], pending...)
			pending = nil
		}
		if hasComment {
			index[lineNo] = append(index[lineNo], comment)
		}
	}
	return index
}

func splitAXMComment(line string) (string, string, bool) {
	inString := false
	escaped := false
	for i, r := range line {
		if escaped {
			escaped = false
			continue
		}
		if r == '\\' {
			escaped = true
			continue
		}
		if r == '"' {
			inString = !inString
			continue
		}
		if r == '#' && !inString {
			return line[:i], cleanAXMComment(line[i:]), true
		}
	}
	return line, "", false
}

func cleanAXMComment(comment string) string {
	comment = strings.TrimSpace(comment)
	comment = strings.TrimPrefix(comment, "#")
	return strings.TrimSpace(comment)
}

func writeLineComments(b *bytes.Buffer, comments commentIndex, line int, indent string) {
	for _, comment := range comments[line] {
		if comment == "" {
			continue
		}
		fmt.Fprintf(b, "%s// %s\n", indent, comment)
	}
}

func stubsFile(module *compiler.Module, opts Options, domain string) ([]byte, error) {
	var b bytes.Buffer
	activities := externalActivities(module)
	comments := newCommentIndex(opts.Source)
	fmt.Fprintf(&b, "package %s\n\n", opts.PackageName)
	fmt.Fprintln(&b, "import (")
	fmt.Fprintln(&b, "\t\"context\"")
	fmt.Fprintln(&b, "\t\"fmt\"")
	fmt.Fprintln(&b, ")")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "type %sActivityImpl struct{}\n\n", domain)
	if len(activities) == 0 {
		fmt.Fprintf(&b, "// %sActivityImpl has no external activities to implement.\n", domain)
	}
	for _, activity := range activities {
		name := exportName(activity.Name)
		writeLineComments(&b, comments, activity.Line, "")
		fmt.Fprintf(&b, "func (%sActivityImpl) %s(ctx context.Context, input %sInput) (%sOutput, error) {\n", domain, name, name, name)
		fmt.Fprintf(&b, "\treturn %sOutput{}, fmt.Errorf(\"%s is not implemented\")\n", name, activity.Name)
		fmt.Fprintln(&b, "}")
		fmt.Fprintln(&b)
	}
	return format.Source(b.Bytes())
}

func writeActivityNameConsts(b *bytes.Buffer, activities []lang.ActivityDecl, comments commentIndex) {
	if len(activities) == 0 {
		return
	}
	fmt.Fprintln(b, "const (")
	for _, activity := range activities {
		writeLineComments(b, comments, activity.Line, "\t")
		fmt.Fprintf(b, "\tActivity%s = %q\n", exportName(activity.Name), activity.Name)
	}
	fmt.Fprintln(b, ")")
	fmt.Fprintln(b)
}

func writeTypes(b *bytes.Buffer, module *compiler.Module, activities []lang.ActivityDecl, comments commentIndex) {
	for _, activity := range activities {
		name := exportName(activity.Name)
		writeLineComments(b, comments, activity.Line, "")
		fmt.Fprintf(b, "type %sInput struct {\n", name)
		for _, input := range activity.Input {
			field := exportName(input.Name)
			writeLineComments(b, comments, input.Line, "\t")
			fmt.Fprintf(b, "\t%s %s `json:%q`\n", field, goType(inferBindingType(module, input)), input.Name)
		}
		fmt.Fprintln(b, "}")
		fmt.Fprintln(b)
		writeLineComments(b, comments, activity.Line, "")
		fmt.Fprintf(b, "type %sOutput struct {\n", name)
		for _, output := range activity.Output {
			field := exportName(output.Name)
			writeLineComments(b, comments, output.Line, "\t")
			fmt.Fprintf(b, "\t%s %s `json:%q`\n", field, goType(output.Type), output.Name)
		}
		fmt.Fprintln(b, "}")
		fmt.Fprintln(b)
	}
}

func writeInterface(b *bytes.Buffer, domain string, activities []lang.ActivityDecl, comments commentIndex) {
	fmt.Fprintf(b, "type %sActivities interface {\n", domain)
	for _, activity := range activities {
		name := exportName(activity.Name)
		writeLineComments(b, comments, activity.Line, "\t")
		fmt.Fprintf(b, "\t%s(ctx context.Context, input %sInput) (%sOutput, error)\n", name, name, name)
	}
	fmt.Fprintln(b, "}")
	fmt.Fprintln(b)
}

func writeLoadAndNew(b *bytes.Buffer, domain string, activities []lang.ActivityDecl, opts Options) {
	path := opts.SourcePath
	if path == "" {
		path = domain + ".axm"
	}
	fmt.Fprintf(b, "func Load%s() (*axiom.App, error) {\n", domain)
	if strings.EqualFold(opts.Format, "toml") {
		fmt.Fprintf(b, "\tplan, err := table.Parse([]byte(%sAXMSource))\n", domain)
		fmt.Fprintln(b, "\tif err != nil {")
		fmt.Fprintln(b, "\t\treturn nil, err")
		fmt.Fprintln(b, "\t}")
		fmt.Fprintf(b, "\treturn &axiom.App{Path: %q, Module: plan.Module()}, nil\n", filepath.ToSlash(path))
	} else {
		fmt.Fprintf(b, "\tmodule, err := axiom.CompileAny([]byte(%sAXMSource), axiom.WithSourceName(%q))\n", domain, filepath.ToSlash(path))
		fmt.Fprintln(b, "\tif err != nil {")
		fmt.Fprintln(b, "\t\treturn nil, err")
		fmt.Fprintln(b, "\t}")
		fmt.Fprintf(b, "\treturn &axiom.App{Path: %q, Module: module}, nil\n", filepath.ToSlash(path))
	}
	fmt.Fprintln(b, "}")
	fmt.Fprintln(b)
	fmt.Fprintf(b, "func New%s(impl %sActivities, opts ...axiom.Option) (*axiom.Engine, error) {\n", domain, domain)
	fmt.Fprintln(b, "\tif impl == nil {")
	fmt.Fprintf(b, "\t\treturn nil, axiom.Error{Code: \"AX500\", Kind: \"config\", Message: %q}\n", domain+" activities implementation is required")
	fmt.Fprintln(b, "\t}")
	fmt.Fprintf(b, "\tapp, err := Load%s()\n", domain)
	fmt.Fprintln(b, "\tif err != nil {")
	fmt.Fprintln(b, "\t\treturn nil, err")
	fmt.Fprintln(b, "\t}")
	fmt.Fprintln(b, "\tregistry := axiom.ActivityRegistry{")
	for _, activity := range activities {
		name := exportName(activity.Name)
		fmt.Fprintf(b, "\t\tActivity%s: adapt%s(impl.%s),\n", name, name, name)
	}
	fmt.Fprintln(b, "\t}")
	fmt.Fprintln(b, "\tall := append([]axiom.Option{axiom.WithActivities(registry)}, opts...)")
	fmt.Fprintln(b, "\treturn app.New(all...)")
	fmt.Fprintln(b, "}")
	fmt.Fprintln(b)
}

func writeAdapters(b *bytes.Buffer, module *compiler.Module, activities []lang.ActivityDecl) {
	for _, activity := range activities {
		name := exportName(activity.Name)
		fmt.Fprintf(b, "func adapt%s(fn func(context.Context, %sInput) (%sOutput, error)) axiom.Activity {\n", name, name, name)
		fmt.Fprintln(b, "\treturn func(ctx context.Context, input axiom.Input) (axiom.Output, error) {")
		fmt.Fprintf(b, "\t\ttypedInput, err := decode%sInput(input)\n", name)
		fmt.Fprintln(b, "\t\tif err != nil {")
		fmt.Fprintln(b, "\t\t\treturn nil, err")
		fmt.Fprintln(b, "\t\t}")
		fmt.Fprintln(b, "\t\tresult, err := fn(ctx, typedInput)")
		fmt.Fprintln(b, "\t\tif err != nil {")
		fmt.Fprintln(b, "\t\t\treturn nil, err")
		fmt.Fprintln(b, "\t\t}")
		fmt.Fprintf(b, "\t\treturn encode%sOutput(result), nil\n", name)
		fmt.Fprintln(b, "\t}")
		fmt.Fprintln(b, "}")
		fmt.Fprintln(b)
		writeInputDecoder(b, module, activity)
		writeOutputEncoder(b, activity)
	}
}

func writeInputDecoder(b *bytes.Buffer, module *compiler.Module, activity lang.ActivityDecl) {
	name := exportName(activity.Name)
	fmt.Fprintf(b, "func decode%sInput(input axiom.Input) (%sInput, error) {\n", name, name)
	fmt.Fprintf(b, "\tvar out %sInput\n", name)
	for _, binding := range activity.Input {
		field := exportName(binding.Name)
		typ := inferBindingType(module, binding)
		fmt.Fprintf(b, "\tif value, ok := input[%q]; ok {\n", binding.Name)
		writeDecodeAssign(b, "out."+field, "value", activity.Name+"."+binding.Name, typ)
		fmt.Fprintln(b, "\t}")
	}
	fmt.Fprintln(b, "\treturn out, nil")
	fmt.Fprintln(b, "}")
	fmt.Fprintln(b)
}

func writeOutputEncoder(b *bytes.Buffer, activity lang.ActivityDecl) {
	name := exportName(activity.Name)
	fmt.Fprintf(b, "func encode%sOutput(output %sOutput) axiom.Output {\n", name, name)
	fmt.Fprintln(b, "\treturn axiom.Output{")
	for _, field := range activity.Output {
		fmt.Fprintf(b, "\t\t%q: output.%s,\n", field.Name, exportName(field.Name))
	}
	fmt.Fprintln(b, "\t}")
	fmt.Fprintln(b, "}")
	fmt.Fprintln(b)
}

func writeDecodeAssign(b *bytes.Buffer, target string, source string, entity string, axmType string) {
	nullable := strings.HasSuffix(axmType, "?")
	base := strings.TrimSuffix(axmType, "?")
	if nullable {
		fmt.Fprintf(b, "\t\tif %s == nil {\n", source)
		fmt.Fprintf(b, "\t\t\t%s = nil\n", target)
		fmt.Fprintln(b, "\t\t} else {")
	}
	indent := "\t\t"
	if nullable {
		indent = "\t\t\t"
	}
	assign := func(format string, args ...any) {
		fmt.Fprintf(b, indent+format+"\n", args...)
	}
	switch {
	case base == "String":
		assign("converted, ok := %s.(string)", source)
		assign("if !ok {")
		assign("\treturn out, axiomTypeError(%q, %s, %q)", entity, source, axmType)
		assign("}")
		if nullable {
			assign("%s = &converted", target)
		} else {
			assign("%s = converted", target)
		}
	case base == "Bool":
		assign("converted, ok := %s.(bool)", source)
		assign("if !ok {")
		assign("\treturn out, axiomTypeError(%q, %s, %q)", entity, source, axmType)
		assign("}")
		if nullable {
			assign("%s = &converted", target)
		} else {
			assign("%s = converted", target)
		}
	case base == "Int":
		assign("converted, ok := axiomToInt(%s)", source)
		assign("if !ok {")
		assign("\treturn out, axiomTypeError(%q, %s, %q)", entity, source, axmType)
		assign("}")
		if nullable {
			assign("%s = &converted", target)
		} else {
			assign("%s = converted", target)
		}
	case base == "Float":
		assign("converted, ok := axiomToFloat(%s)", source)
		assign("if !ok {")
		assign("\treturn out, axiomTypeError(%q, %s, %q)", entity, source, axmType)
		assign("}")
		if nullable {
			assign("%s = &converted", target)
		} else {
			assign("%s = converted", target)
		}
	case base == "Object" || strings.HasPrefix(base, "Map<"):
		assign("converted, ok := %s.(map[string]any)", source)
		assign("if !ok {")
		assign("\treturn out, axiomTypeError(%q, %s, %q)", entity, source, axmType)
		assign("}")
		if nullable {
			assign("%s = &converted", target)
		} else {
			assign("%s = converted", target)
		}
	case strings.HasPrefix(base, "List<"):
		elem := strings.TrimSuffix(strings.TrimPrefix(base, "List<"), ">")
		assign("converted, ok := axiomTo%sSlice(%s)", exportName(elem), source)
		assign("if !ok {")
		assign("\treturn out, axiomTypeError(%q, %s, %q)", entity, source, axmType)
		assign("}")
		if nullable {
			assign("%s = &converted", target)
		} else {
			assign("%s = converted", target)
		}
	default:
		if nullable {
			assign("converted := %s", source)
			assign("%s = &converted", target)
		} else {
			assign("%s = %s", target, source)
		}
	}
	if nullable {
		fmt.Fprintln(b, "\t\t}")
	}
}

